#!/usr/bin/env python3
"""Generate migrations/0001_init.sql (SQLite/D1) from scripts/pg-schema.json.

pg-schema.json is a read-only dump of the live Supabase `public` schema (columns + index keys).
Type map: uuid/text/date/timestamptz/jsonb/text[] -> TEXT, bool -> INTEGER, int -> INTEGER,
float -> REAL. No foreign keys on purpose (see docs/MIGRATION-cloudflare.md 1.2). Dropped: content_embeddings
(pgvector, 0 rows, unused).
"""
import json, re, sys, pathlib
root = pathlib.Path(__file__).parent
schema = json.load(open(root / "pg-schema.json"))
DROP = {"content_embeddings"}
NOW = "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))"
UUID = "(lower(hex(randomblob(16))))"
SYNCED_COL = {"user_id", "updated_at"}

def ctype(c):
    u = c["u"]
    if u in ("bool",): return "INTEGER"
    if u in ("int4", "int8"): return "INTEGER"
    if u in ("float4", "float8"): return "REAL"
    return "TEXT"

def default(c):
    d = c["d"]
    if d is None: return None
    if d == "now()": return NOW
    if d == "gen_random_uuid()": return UUID
    if d in ("true", "false"): return "1" if d == "true" else "0"
    if d.startswith("nextval("): return None
    if d == "auth.uid()": return None
    if d in ("'{}'::text[]",): return "'[]'"
    m = re.fullmatch(r"'(.*)'::(text|jsonb)", d)
    if m: return "'" + m.group(1) + "'"
    if re.fullmatch(r"-?\d+(\.\d+)?", d): return d
    print("UNHANDLED DEFAULT", c["n"], d, file=sys.stderr); return None

out = ["-- GENERATED by scripts/gen-d1-schema.py from the live Supabase public schema. Do not edit by hand.",
       "-- Types: uuid/timestamptz/jsonb/arrays are TEXT (ISO UTC, JSON), booleans are INTEGER 0/1. No FKs.", ""]
tables = []
for t in schema:
    name = t["table_name"]
    if name in DROP: continue
    cols = t["cols"]
    pk = next((i["cols"] for i in t["idx"] if i["pk"]), None)
    lines = []
    for c in cols:
        is_serial = (c["d"] or "").startswith("nextval(")
        if is_serial and pk == [c["n"]]:
            lines.append(f'  "{c["n"]}" INTEGER PRIMARY KEY AUTOINCREMENT'); continue
        s = f'  "{c["n"]}" {ctype(c)}'
        if c["null"] == "NO": s += " NOT NULL"
        dv = default(c)
        if dv is not None: s += f" DEFAULT {dv}"
        lines.append(s)
    if pk and not any("AUTOINCREMENT" in l for l in lines):
        lines.append("  PRIMARY KEY (" + ", ".join(f'"{k}"' for k in pk) + ")")
    out.append(f'CREATE TABLE IF NOT EXISTS "{name}" (\n' + ",\n".join(lines) + "\n);")
    for i in t["idx"]:
        if i["uq"] and not i["pk"]:
            n = f'uq_{name}_' + "_".join(i["cols"])
            out.append(f'CREATE UNIQUE INDEX IF NOT EXISTS "{n}" ON "{name}" (' + ", ".join(f'"{k}"' for k in i["cols"]) + ");")
    names = {c["n"] for c in cols}
    if SYNCED_COL <= names:
        out.append(f'CREATE INDEX IF NOT EXISTS "ix_{name}_user_updated" ON "{name}" ("user_id", "updated_at");')
    tables.append(name)
    out.append("")
(root.parent / "migrations" / "0001_init.sql").write_text("\n".join(out))
(root / "tables.json").write_text(json.dumps(tables))

# src/tables.ts: the Worker's per-table registry (column kinds drive bool/JSON/timestamp conversion).
def kind(c):
    u = c["u"]
    if u == "bool": return "b"
    if u == "jsonb": return "j"
    if u == "_text": return "a"
    if u == "timestamptz": return "t"
    if u in ("int4", "int8", "float4", "float8"): return "n"
    return "s"
reg = {}
for t in schema:
    if t["table_name"] in DROP: continue
    names = {c["n"] for c in t["cols"]}
    reg[t["table_name"]] = {
        "pk": next((i["cols"] for i in t["idx"] if i["pk"]), ["id"]),
        "cols": {c["n"]: kind(c) for c in t["cols"]},
        "owned": "user_id" in names,
        "synced": {"updated_at", "sync_version"} <= names,
    }
sync = json.load(open(root / "sync-tables.json"))
ts = ("// GENERATED by scripts/gen-d1-schema.py. Do not edit by hand.\n"
      "// Column kinds: b bool, j json, a text[] (stored as JSON), t timestamptz (ISO ms UTC), n number, s text.\n"
      "export type Kind = 'b' | 'j' | 'a' | 't' | 'n' | 's';\n"
      "export interface TableDef { pk: string[]; cols: Record<string, Kind>; owned: boolean; synced: boolean }\n"
      f"export const TABLES: Record<string, TableDef> = {json.dumps(reg, indent=1)};\n"
      f"/** Tables the app's TableSyncers push to / pull from. */\nexport const SYNC_TABLES: string[] = {json.dumps(sync)};\n")
(root.parent / "src" / "tables.ts").write_text(ts)
print(len(tables), "tables written")
