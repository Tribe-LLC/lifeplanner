#!/usr/bin/env python3
"""Generate migrations/0003_gamification.sql: SQLite ports of the Supabase plpgsql gamification triggers.

Source of truth for the behaviour is the live Postgres functions (trg_*_gamification, award_xp,
check_and_award_badges, update_challenge_progress, calculate_level_from_xp), dumped 2026-10-09.
SQLite triggers have no procedural flow, so each trigger inserts its gamification_log row with
xp_awarded = -1 (a "fresh" sentinel; a duplicate insert is ignored and leaves the old row), guards every later
statement on that sentinel (the plpgsql `IF NOT FOUND THEN RETURN`), and finally writes the real xp.
Inserts inside triggers use ON CONFLICT ... DO NOTHING, not INSERT OR IGNORE: SQLite lets an outer
statement's conflict algorithm (an upsert's UPDATE path) override OR IGNORE and raise UNIQUE errors.
Every server-side UPDATE also bumps sync_version, as the Postgres BEFORE UPDATE sync trigger did.
"""
import pathlib
NOW = "strftime('%Y-%m-%dT%H:%M:%fZ','now')"
UUID = ("(lower(hex(randomblob(4)))||'-'||lower(hex(randomblob(2)))||'-4'||substr(lower(hex(randomblob(2))),2)"
        "||'-'||substr('89ab',abs(random())%4+1,1)||substr(lower(hex(randomblob(2))),2)||'-'||lower(hex(randomblob(6))))")
out = ["-- GENERATED by scripts/gen-gamification.py. Do not edit by hand.", ""]

# level_thresholds: level L is reached at 75*L*(L-1) xp (calculate_level_from_xp: floor(100*L*1.5) per level)
out.append("CREATE TABLE IF NOT EXISTS level_thresholds (level INTEGER PRIMARY KEY, min_xp INTEGER NOT NULL);")
# D1 caps compound SELECT / multi-row VALUES terms very low, so: one statement per row.
for l in range(1, 1001):
    out.append(f"INSERT OR REPLACE INTO level_thresholds VALUES ({l},{75*l*(l-1)});")
out.append("")

def level(x): return f"(SELECT MAX(level) FROM level_thresholds WHERE min_xp <= ({x}))"

def fresh(uid, ev, src):
    return (f"EXISTS (SELECT 1 FROM gamification_log WHERE user_id = {uid} AND event_type = '{ev}' "
            f"AND source_id = {src} AND xp_awarded = -1)")

def award(uid, amt, guard):
    return (f"INSERT INTO user_progress (user_id, total_xp, current_level, updated_at)\n"
            f"  SELECT {uid}, {amt}, {level(amt)}, {NOW} WHERE {guard}\n"
            f"  ON CONFLICT (user_id) DO UPDATE SET total_xp = user_progress.total_xp + excluded.total_xp,\n"
            f"    current_level = {level('user_progress.total_xp + excluded.total_xp')},\n"
            f"    updated_at = {NOW}, sync_version = user_progress.sync_version + 1;")

XP = ("CASE c.challenge_type WHEN 'DAILY_CHECK_IN' THEN 10 WHEN 'DAILY_JOURNAL' THEN 15 WHEN 'DAILY_HABIT' THEN 20 "
      "WHEN 'WEEKLY_GOALS' THEN 50 WHEN 'WEEKLY_HABITS' THEN 75 WHEN 'WEEKLY_JOURNAL' THEN 50 "
      "WHEN 'WEEKLY_MILESTONE' THEN 60 WHEN 'MONTHLY_COMPLETION' THEN 200 WHEN 'MONTHLY_STREAK' THEN 300 "
      "WHEN 'MONTHLY_BALANCED' THEN 250 WHEN 'PERFECT_DAY' THEN 100 WHEN 'CATEGORY_FOCUS' THEN 150 "
      "WHEN 'EARLY_RISER' THEN 100 ELSE 0 END")
ACT = {"habit": ("DAILY_HABIT", "WEEKLY_HABITS"), "journal": ("DAILY_JOURNAL", "WEEKLY_JOURNAL"),
       "goal": ("WEEKLY_GOALS", "MONTHLY_COMPLETION"), "milestone": ("WEEKLY_MILESTONE",)}

def challenge(uid, act, guard):
    types = ",".join(f"'{t}'" for t in ACT[act])
    cond = (f"c.user_id = {uid} AND c.challenge_type IN ({types}) AND c.is_completed = 0 AND c.is_deleted = 0 "
            f"AND c.end_date >= date('now')")
    done = "c.current_progress + 1 >= c.target_progress"
    a = (f"INSERT INTO user_progress (user_id, total_xp, current_level, updated_at)\n"
         f"  SELECT {uid}, SUM({XP}), {level('SUM('+XP+')')}, {NOW} FROM challenges c\n"
         f"  WHERE {cond} AND {done} AND {guard} HAVING COUNT(*) > 0\n"
         f"  ON CONFLICT (user_id) DO UPDATE SET total_xp = user_progress.total_xp + excluded.total_xp,\n"
         f"    current_level = {level('user_progress.total_xp + excluded.total_xp')},\n"
         f"    updated_at = {NOW}, sync_version = user_progress.sync_version + 1;")
    xp_plain = XP.replace("c.challenge_type", "challenges.challenge_type")
    d2 = "challenges.current_progress + 1 >= challenges.target_progress"
    b = (f"UPDATE challenges SET current_progress = current_progress + 1, updated_at = {NOW},\n"
         f"  sync_version = sync_version + 1 + (CASE WHEN {d2} THEN 1 ELSE 0 END),\n"
         f"  is_completed = CASE WHEN {d2} THEN 1 ELSE 0 END,\n"
         f"  completed_at = CASE WHEN {d2} THEN {NOW} ELSE completed_at END,\n"
         f"  xp_earned = CASE WHEN {d2} THEN {xp_plain} ELSE xp_earned END\n"
         f"  WHERE user_id = {uid} AND challenge_type IN ({types}) AND is_completed = 0 AND is_deleted = 0\n"
         f"  AND end_date >= date('now') AND {guard};")
    return a + "\n" + b

BADGES = [("STREAK_3",3,"s"),("STREAK_7",7,"s"),("STREAK_14",14,"s"),("STREAK_30",30,"s"),("STREAK_100",100,"s"),
          ("GOAL_1",1,"g"),("GOAL_5",5,"g"),("GOAL_10",10,"g"),("GOAL_25",25,"g"),("GOAL_50",50,"g"),
          ("HABIT_STARTER",1,"h"),("HABIT_5",5,"h"),("JOURNAL_FIRST",1,"j"),("JOURNAL_10",10,"j"),("JOURNAL_30",30,"j")]

def badge_row(uid, typ): return f"{UUID}, {uid}, {typ}, {NOW}, 1, {NOW}, 0, 0"
BCOLS = "(id, user_id, badge_type, earned_at, is_new, updated_at, is_deleted, sync_version)"

out.append("CREATE TABLE IF NOT EXISTS badge_rules (bt TEXT PRIMARY KEY, req INTEGER NOT NULL, kind TEXT NOT NULL);")
for b, r, k in BADGES:
    out.append(f"INSERT OR REPLACE INTO badge_rules VALUES ('{b}', {r}, '{k}');")
out.append("")

def badges(uid, guard):
    checks = "SELECT bt, req, kind FROM badge_rules"
    first = (f"INSERT INTO badges {BCOLS}\n  SELECT {badge_row(uid, chr(39)+'FIRST_STEP'+chr(39))} "
             f"FROM user_progress p WHERE p.user_id = {uid} AND {guard}\n"
             f"  AND (SELECT COUNT(*) FROM gamification_log WHERE user_id = {uid} AND event_type = 'goal_created') >= 1\n  ON CONFLICT (user_id, badge_type) DO NOTHING;")
    rest = (f"INSERT INTO badges {BCOLS}\n  SELECT {badge_row(uid, 'k.bt')} FROM user_progress p, ({checks}) k\n"
            f"  WHERE p.user_id = {uid} AND {guard} AND (CASE k.kind WHEN 's' THEN p.current_streak WHEN 'g' THEN p.goals_completed "
            f"WHEN 'h' THEN p.habits_completed ELSE p.journal_entries_count END) >= k.req\n  ON CONFLICT (user_id, badge_type) DO NOTHING;")
    return first + "\n" + rest

def bump(col, uid, guard):
    return (f"UPDATE user_progress SET {col} = {col} + 1, updated_at = {NOW}, sync_version = sync_version + 1 "
            f"WHERE user_id = {uid} AND {guard};")

def trigger(name, when_ev, table, cond, body):
    out.append(f"DROP TRIGGER IF EXISTS {name};")
    out.append(f"CREATE TRIGGER {name} {when_ev} ON {table} FOR EACH ROW WHEN {cond}\nBEGIN\n" + "\n".join(body) + "\nEND;\n")

def log_start(ev, src): return f"INSERT INTO gamification_log (user_id, event_type, source_id, xp_awarded) VALUES (NEW.user_id, '{ev}', {src}, -1) ON CONFLICT (user_id, event_type, source_id) DO NOTHING;"
def log_end(ev, src, xp): return f"UPDATE gamification_log SET xp_awarded = {xp} WHERE user_id = NEW.user_id AND event_type = '{ev}' AND source_id = {src} AND xp_awarded = -1;"
U = "NEW.user_id"

# goals
g = fresh(U, "goal_created", "NEW.id")
trigger("trg_goal_created_gamification", "AFTER INSERT", "goals", "NEW.is_deleted = 0",
        [log_start("goal_created", "NEW.id"), award(U, 5, g), badges(U, g), log_end("goal_created", "NEW.id", 5)])
g = fresh(U, "goal_completed", "NEW.id")
trigger("trg_goal_completed_gamification", "AFTER UPDATE", "goals",
        "NEW.is_deleted = 0 AND NEW.status = 'COMPLETED' AND OLD.status <> 'COMPLETED'",
        [log_start("goal_completed", "NEW.id"), award(U, 50, g), bump("goals_completed", U, g),
         challenge(U, "goal", g), badges(U, g), log_end("goal_completed", "NEW.id", 50)])
# milestones
g = fresh(U, "milestone_completed", "NEW.id")
trigger("trg_milestone_completed_gamification", "AFTER UPDATE", "milestones",
        "NEW.is_deleted = 0 AND NEW.is_completed = 1 AND OLD.is_completed = 0",
        [log_start("milestone_completed", "NEW.id"), award(U, 15, g), challenge(U, "milestone", g),
         log_end("milestone_completed", "NEW.id", 15)])
# journal
g = fresh(U, "journal_entry", "NEW.id")
trigger("trg_journal_entry_gamification", "AFTER INSERT", "journal_entries", "NEW.is_deleted = 0",
        [log_start("journal_entry", "NEW.id"), award(U, 10, g), bump("journal_entries_count", U, g),
         challenge(U, "journal", g), badges(U, g), log_end("journal_entry", "NEW.id", 10)])
# habit check-in
g = fresh(U, "habit_checkin", "NEW.id")
hx = "(5 + 2 * COALESCE((SELECT h.current_streak FROM habits h WHERE h.id = NEW.habit_id AND h.user_id = NEW.user_id), 0))"
trigger("trg_habit_checkin_gamification", "AFTER INSERT", "habit_check_ins", "NEW.is_deleted = 0",
        [log_start("habit_checkin", "NEW.id"), award(U, hx, g), bump("habits_completed", U, g),
         challenge(U, "habit", g), badges(U, g), log_end("habit_checkin", "NEW.id", hx)])
# focus sessions
DUR = "(CASE WHEN NEW.planned_duration_minutes = 0 AND NEW.actual_duration_seconds > 0 THEN NEW.actual_duration_seconds / 60 ELSE NEW.planned_duration_minutes END)"
# GREATEST((v*0.5)::int, 1): float8 -> int rounds half to even
HALF = f"(CASE WHEN {DUR} % 2 = 0 THEN {DUR} / 2 WHEN ({DUR} / 2) % 2 = 0 THEN {DUR} / 2 ELSE {DUR} / 2 + 1 END)"
FXP = (f"(CASE WHEN {DUR} >= 60 THEN 40 WHEN {DUR} >= 45 THEN 30 WHEN {DUR} >= 25 THEN 20 WHEN {DUR} >= 15 THEN 10 "
       f"WHEN {HALF} > 1 THEN {HALF} ELSE 1 END)")
g = fresh(U, "focus_session", "NEW.id")
FCNT = f"(SELECT COUNT(*) FROM gamification_log WHERE user_id = {U} AND event_type = 'focus_session')"
def fbadge(typ, cond):
    return (f"INSERT INTO badges {BCOLS}\n  SELECT {badge_row(U, chr(39)+typ+chr(39))} WHERE {g} AND {cond}\n  ON CONFLICT (user_id, badge_type) DO NOTHING;")
fbody = [log_start("focus_session", "NEW.id"), award(U, FXP, g),
         fbadge("FOCUS_FIRST", f"{FCNT} >= 1"), fbadge("FOCUS_10", f"{FCNT} >= 10"),
         fbadge("FOCUS_50", f"{FCNT} >= 50"), fbadge("FOCUS_HOUR", f"{DUR} >= 60"),
         log_end("focus_session", "NEW.id", FXP)]
trigger("trg_focus_session_insert_gamification", "AFTER INSERT", "focus_sessions",
        "NEW.is_deleted = 0 AND NEW.was_completed = 1", fbody)
trigger("trg_focus_session_update_gamification", "AFTER UPDATE", "focus_sessions",
        "NEW.is_deleted = 0 AND NEW.was_completed = 1 AND OLD.was_completed = 0", fbody)
# beginner objectives
g = fresh(U, "objective_completed", "NEW.id")
obody = [log_start("objective_completed", "NEW.id"), award(U, "NEW.xp_awarded", g),
         log_end("objective_completed", "NEW.id", "NEW.xp_awarded")]
trigger("trg_beginner_objective_completed_insert", "AFTER INSERT", "beginner_objectives",
        "NEW.is_completed = 1 AND NEW.xp_awarded > 0", obody)
trigger("trg_beginner_objective_completed", "AFTER UPDATE", "beginner_objectives",
        "NEW.is_completed = 1 AND OLD.is_completed = 0 AND NEW.xp_awarded > 0", obody)

pathlib.Path(__file__).parent.parent.joinpath("migrations/0003_gamification.sql").write_text("\n".join(out))
print("ok")
